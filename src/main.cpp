// Everything gfx needs lives in one struct. sampleTask updates it under `mtx`;
// drawTask copies it under `mtx` and then draws from its private copy, so a frame
// never sees a half-updated sample or history ring.
// One reading of the power/environment sensors (powerTask -> gfx and -> MQTT).
struct PowerS {
  uint32_t t;        // millis()
  float v, i, p;     // battery V, A (+ = charging), W (+ = charging)
  float soc;         // %, from pack voltage
  int   chg;         // 1 charging, 0 idle/full, -1 discharging
  float tImu, tChip; // degC (BMI270, ESP32-P4 die)
  int   rssi;        // dBm, 0 = not connected
  uint32_t heap;     // free internal heap, bytes
  float mic;         // dBFS of the internal mic, -99 = mic off
  float avg;         // ~10 s average of p, W (+ charging)
  float wh;          // energy stored in the pack, Wh (capacity x charge %)
  float eta;         // minutes to empty (avg < 0) or to full (avg > 0); -1 = not meaningful
  int   bri, scr;    // screen brightness 0..255 and on/off, so the viewer can show them
};

