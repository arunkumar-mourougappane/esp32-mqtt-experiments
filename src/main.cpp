// Panel frames: restore the cached, dimmed dashboard under the panel, draw the panel, push only those strips.
static void drawMenuFrame(const Snap &s) {
  const int bottom = (int)((menuP - 1.0f) * MENU_H) + MENU_H;
  for (int i = 0; i < CACHE_STRIPS && i * STRIP_H < bottom; i++) {
    pollTouch();
    if (!menuOpen) return;                                 // closed meanwhile: the next frame redraws everything
    g.oy = i * STRIP_H;
    memcpy(canvas.getBuffer(), bgCache + (size_t)i * SCR_W * STRIP_H, (size_t)SCR_W * STRIP_H * 2);
    drawMenu(s);
    canvas.pushSprite(0, g.oy);
  }
}

// Opening the panel: do not re-render the dashboard. Read the picture that is already on the screen back from the
// panel framebuffer, halve every pixel's brightness (RGB565: shift right one and mask the bits that crossed fields,
// two pixels per 32-bit word), keep the strips the panel will cover, and push them all back.
static void freezeDashboard() {
  uint32_t t0 = millis();
  const size_t words = (size_t)SCR_W * STRIP_H / 2, bytes = (size_t)SCR_W * STRIP_H * 2;
  for (int i = 0; i < SCR_H / STRIP_H; i++) {
    const int y = i * STRIP_H;
    M5.Display.readRect(0, y, SCR_W, STRIP_H, (lgfx::rgb565_t *)canvas.getBuffer());
    uint32_t *w = (uint32_t *)canvas.getBuffer();
    for (size_t k = 0; k < words; k++) w[k] = (w[k] >> 1) & 0x7BEF7BEFu;
    if (i < CACHE_STRIPS) memcpy(bgCache + (size_t)i * SCR_W * STRIP_H, canvas.getBuffer(), bytes);
    canvas.pushSprite(0, y);
  }
  bgReady = true;
  Serial.printf("panel: dashboard frozen in %u ms\n", (unsigned)(millis() - t0));
}

static void draw(const Snap &s, int fps) {
  const int gap = 8, y1 = 84, h1 = 500;
  const int y2 = y1 + h1 + gap, h2 = 232;
  const int y3 = y2 + h2 + gap, h3 = 200;
  const int y4 = y3 + h3 + gap, h4 = SCR_H - y4 - 8;

  if (menuOpen && !bgReady) { freezeDashboard(); return; }
  if (menuOpen && bgReady) { drawMenuFrame(s); return; }

  for (int y = 0; y < SCR_H; y += STRIP_H) {
    pollTouch();                                 // between strips: keeps touch responsive at ~13 fps
    g.oy = y;
    canvas.fillSprite(C_BG);
    drawHeader(fps, s.pw.rssi);
    drawScope(s, y1, h1);
    drawDials(s, y2, h2);
    drawLinear(s, y3, h3);
    drawPower(s, y4, h4);
    canvas.pushSprite(0, y);
  }
}

// The backlight is linear PWM, but the eye is not: equal duty steps look wildly uneven. Squaring the logical
// level spreads the slider evenly across what you see; the offset keeps the lowest setting readable.
static uint8_t backlightDuty(uint8_t lvl) {
  if (lvl == 0) return 0;
  float x = lvl / 255.0f;
  return (uint8_t)(8.0f + 247.0f * x * x + 0.5f);
}

static void drawTask(void *) {
  Serial.printf("gfx task on core %d\n", xPortGetCoreID());
  static Snap snap;                              // private copy (too big for the task stack)
  uint32_t fpsT = millis(); int frames = 0, fps = 0;
  for (;;) {
    if (briWant >= 0 || scrWant >= 0) {
      uint32_t t0 = millis();
      if (briWant >= 0) { briLevel = briWant; briWant = -1; }
      if (scrWant >= 0) { scrOn = scrWant; scrWant = -1; if (!scrOn) menuClose(); }
      M5.Display.setBrightness(scrOn ? backlightDuty(briLevel) : 0);
      Serial.printf("display apply: screen=%d level=%d duty=%d (read back %d) took %u ms\n", (int)scrOn, (int)briLevel,
                    (int)backlightDuty(briLevel), (int)M5.Display.getBrightness(), (unsigned)(millis() - t0));
    }
    pollTouch();
    menuP = menuOpen ? fminf(1.0f, menuP + 0.34f) : fmaxf(0.0f, menuP - 0.34f);
    if (!scrOn) { vTaskDelay(pdMS_TO_TICKS(25)); continue; }      // backlight off: skip drawing, keep polling touch
    if (menuOpen && bgReady && menuP >= 1.0f) {                   // panel fully open: redraw only when something changed
      uint32_t nowm = millis();
      if (!menuDirty && nowm - menuTick < 1000) { vTaskDelay(pdMS_TO_TICKS(15)); continue; }
      menuDirty = false; menuTick = nowm;
    }

    xSemaphoreTake(mtx, portMAX_DELAY);
    memcpy(&snap, &live, sizeof snap);
    xSemaphoreGive(mtx);

    draw(snap, fps);

    frames++;
    uint32_t now = millis();
    if (now - fpsT >= 1000) {
      fps = frames * 1000 / (now - fpsT); frames = 0; fpsT = now; gfxFps = fps;
      Serial.printf("gfx %d fps\n", fps);
    }
    vTaskDelay(1);                               // let the idle task run
  }
}

// ---------- sampling ----------
// Fixed 100 Hz, never touches the network. Every 2nd sample is queued for transmit (50 Hz).
static void sampleTask(void *) {
  Serial.printf("sample task on core %d\n", xPortGetCoreID());
  float roll = 0, pitch = 0, yaw = 0, grav[3] = {0, 0, 0};
  bool first = true;
  TickType_t last = xTaskGetTickCount();
  uint32_t prevUs = micros(), tick = 0;
  for (;;) {
    uint32_t nowUs = micros();
    float dt = (nowUs - prevUs) * 1e-6f;
    prevUs = nowUs;

    float a[3], g[3];
    xSemaphoreTake(i2cMtx, portMAX_DELAY);
    M5.Imu.update();
    xSemaphoreGive(i2cMtx);
    M5.Imu.getAccel(&a[0], &a[1], &a[2]);
    M5.Imu.getGyro(&g[0], &g[1], &g[2]);
    orientation(a[0], a[1], a[2], g[0], g[1], g[2], dt, roll, pitch, yaw);

    float lin[3];
    for (int i = 0; i < 3; i++) {                // gravity = ~0.5 s low-pass of accel
      if (first) grav[i] = a[i];
      grav[i] += 0.02f * (a[i] - grav[i]);
      lin[i] = a[i] - grav[i];
    }
    first = false;

    xSemaphoreTake(mtx, portMAX_DELAY);
    for (int i = 0; i < 3; i++) {
      live.a[i] = a[i]; live.g[i] = g[i];
      live.accHist[i][live.head] = a[i];
      live.linHist[i][live.head] = lin[i];
    }
    live.roll = roll * RAD_TO_DEG; live.pitch = pitch * RAD_TO_DEG; live.yaw = yaw * RAD_TO_DEG;
    live.head = (live.head + 1) % HIST;
    xSemaphoreGive(mtx);

    if ((++tick & 1) == 0) {
      Sample m = {millis(), a[0], a[1], a[2], g[0], g[1], g[2],
                 (float)(roll * RAD_TO_DEG), (float)(pitch * RAD_TO_DEG), (float)(yaw * RAD_TO_DEG)};
      xQueueSend(sampleQ, &m, 0);                // drop if the tx task is behind
    }
    vTaskDelayUntil(&last, pdMS_TO_TICKS(10));
  }
}

// ---------- power / environment ----------
// 10 Hz. The INA226 sits on the battery path (2S pack), so this is battery power, not total system draw:
// on USB it shows charge current, on battery it shows the discharge of everything the tablet runs.
static void powerTask(void *) {
  Serial.printf("power task on core %d\n", xPortGetCoreID());
  TickType_t last = xTaskGetTickCount();
  float tChip = 0, tImu = 0;
  int rssi = 0; uint32_t heap = 0, tick = 0;
  float pAvg = 0; bool avgInit = false, rssiOk = true;
  for (;;) {
    PowerS p = {};
    p.t = millis();
    xSemaphoreTake(i2cMtx, portMAX_DELAY);
    p.v   = M5.Power.getBatteryVoltage() / 1000.0f;
    p.i   = M5.Power.getBatteryCurrent() / 1000.0f;
    if ((tick % 10) == 0) { float t; if (M5.Imu.getTemp(&t)) tImu = t; }
    auto cs = M5.Power.getChargeState();
    xSemaphoreGive(i2cMtx);
    p.p   = p.v * p.i;
    p.soc = (float)M5.Power.getBatteryLevel();
    p.chg = cs == m5::charge_state_t::charging ? 1
          : cs == m5::charge_state_t::discharging ? -1 : 0;

    if ((tick % 10) == 0) {                       // 1 Hz extras
      tChip = temperatureRead();
      heap  = ESP.getFreeHeap();
      if (millis() - txBeat > TX_HANG_MS) recoveryRestart("tx task stopped responding");
      if ((tick % 100) == 50) memLine("mem");     // every 10 s
    }
    // WiFi.RSSI() is an RPC to the C6 Wi-Fi coprocessor. When that RPC times out it blocks the caller for 5 s and
    // leaks memory every time, which starved the TLS link. So: ask rarely, and stop for good after one failure.
    if (rssiOk && (tick % 100) == 0 && WiFi.status() == WL_CONNECTED) {
      int r = WiFi.RSSI();
      if (r == 0) { rssiOk = false; Serial.println("rssi unavailable, not asking again"); }
      rssi = r;
    }
    p.tImu = tImu; p.tChip = tChip; p.rssi = rssi; p.heap = heap; p.mic = micOn ? micLevel : -99.0f;
    if (!avgInit) { pAvg = p.p; avgInit = true; }
    pAvg += 0.01f * (p.p - pAvg);                    // 10 Hz, ~10 s time constant
    p.avg = pAvg; p.bri = briLevel; p.scr = scrOn;
    p.wh  = BAT_WH * p.soc / 100.0f;
    p.eta = pAvg < -ETA_MIN_W ? p.wh / -pAvg * 60.0f
          : pAvg >  ETA_MIN_W ? (BAT_WH - p.wh) / pAvg * 60.0f : -1.0f;   // charge taper makes "to full" optimistic

    xSemaphoreTake(mtx, portMAX_DELAY);
    live.pw = p;
    live.pHist[live.pHead] = p.p;
    live.pHead = (live.pHead + 1) % PHIST;
    xSemaphoreGive(mtx);
    xQueueSend(powerQ, &p, 0);

    tick++;
    vTaskDelayUntil(&last, pdMS_TO_TICKS(100));
  }
}

// ---------- microphone ----------
// Off by default. "mic on" / "mic off" on tab5/cmd starts/stops capture; while on, 32 ms PCM blocks go
// to tab5/audio. The port is only opened while streaming.
static float micDbfs(const int16_t *b, int n) {       // RMS of the block, dB re full scale
  float mean = 0; for (int i = 0; i < n; i++) mean += b[i]; mean /= n;   // drop DC
  float acc = 0;  for (int i = 0; i < n; i++) { float d = b[i] - mean; acc += d * d; }
  float rms = sqrtf(acc / n);
  return rms < 1.0f ? -99.0f : 20.0f * log10f(rms / 32768.0f);
}

static void micTask(void *) {
  Serial.printf("mic task on core %d\n", xPortGetCoreID());
  static AudioChunk buf[3];                       // one being captured, one queued, one spare
  int slot = 0;
  for (;;) {
    if (!micWant) {
      if (micOn) { M5.Mic.end(); micOn = false; micLevel = -99; Serial.println("mic off"); }
      vTaskDelay(pdMS_TO_TICKS(50));
      continue;
    }
    if (!micOn) {
      M5.Speaker.end();                           // codec/I2S is shared with the speaker path
      M5.Mic.config([]{ auto c = M5.Mic.config(); c.sample_rate = MIC_RATE; c.stereo = false; return c; }());
      if (!M5.Mic.begin()) { Serial.println("mic begin failed"); micWant = false; continue; }
      micOn = true; slot = 0;
      Serial.println("mic on");
      M5.Mic.record(buf[0].pcm, MIC_N, MIC_RATE);
    }
    // Block until the pending buffer is filled, arm the next one, then hand the filled one on.
    int cur = slot; slot = (slot + 1) % 3;
    M5.Mic.record(buf[slot].pcm, MIC_N, MIC_RATE);     // queue next (2 request slots)
    while (M5.Mic.isRecording() > 1 && micWant) vTaskDelay(1);   // wait until `cur` is complete
    micLevel = micDbfs(buf[cur].pcm, MIC_N);
    xQueueSend(audioQ, &buf[cur], 0);              // copies; dropped if the tx task is behind
  }
}

// ---------- networking (txTask only) ----------
static uint32_t lastMqttTry, lastWifiTry, pubCount, rateT, lastOnline;
static int failStreak;


static void netService() {
  uint32_t now = millis();
  wifiUp = WiFi.status() == WL_CONNECTED;
  if (wifiUp) wifiDownSince = 0;
  else { if (!wifiDownSince) wifiDownSince = now | 1; mqttDownSince = 0; }
  if (!wifiUp) {
    if (now - lastWifiTry > 10000 || lastWifiTry == 0) { lastWifiTry = now ? now : 1; WiFi.begin(WIFI_SSID, WIFI_PASS); }
    return;
  }
  // Certificate validity dates are checked, so the clock must be set first (NTP; needs internet).
  static bool ntpStarted = false;
  if (time(nullptr) < 1700000000) {
    if (!ntpStarted) { configTime(0, 0, "pool.ntp.org", "time.google.com"); ntpStarted = true; }
    return;
  }
  if (!mqtt.connected()) {
    if (now - lastMqttTry > 3000) {
      lastMqttTry = now;
      String id = "tab5-" + String((uint32_t)ESP.getEfuseMac(), HEX);
      if (mqtt.connect(id.c_str(), MQTT_USER, MQTT_PASS)) {
        mqtt.subscribe(MQTT_TOPIC_CMD);
        if (failStreak) Serial.printf("mqtt connected again after %d failed attempts\n", failStreak);
        failStreak = 0; wdRestarts = 0;
      } else {
        char err[96] = "";
        wifiClient.lastError(err, sizeof err);
        Serial.printf("mqtt connect failed: state=%d tls='%s'\n", mqtt.state(), err);
        memLine("mem");
        // A dead broker also fails every attempt, so do not bounce Wi-Fi more than once a minute.
        static uint32_t lastReset;
        if (++failStreak >= WIFI_RESET_EVERY && now - lastReset > 60000) {
          lastReset = now;
          Serial.printf("RECOVERY resetting Wi-Fi after %d failed connects\n", failStreak);
          wifiClient.stop();
          WiFi.disconnect();
          lastWifiTry = 0;                    // reconnect on the next pass
        }
      }
    }
    return;
  }
  mqtt.loop();
}

static void publish(const Sample &m) {
  char p[192];
  int n = snprintf(p, sizeof p,
    "{\"t\":%lu,\"ax\":%.4f,\"ay\":%.4f,\"az\":%.4f,\"gx\":%.3f,\"gy\":%.3f,\"gz\":%.3f,"
    "\"roll\":%.2f,\"pitch\":%.2f,\"yaw\":%.2f}",
    (unsigned long)m.t, m.ax, m.ay, m.az, m.gx, m.gy, m.gz, m.roll, m.pitch, m.yaw);
  if (n > 0 && mqtt.publish(MQTT_TOPIC, p)) { pubCount++; pubTotal++; }
}

static void onMessage(char *topic, uint8_t *pl, unsigned len) {
  if (strcmp(topic, MQTT_TOPIC_CMD) != 0) return;
  char c[24] = {}; memcpy(c, pl, len < sizeof c - 1 ? len : sizeof c - 1);
  if (!strcmp(c, "mic on"))     micWant = true;
  if (!strcmp(c, "mic off"))    micWant = false;
  if (!strcmp(c, "screen on"))  scrWant = 1;
  if (!strcmp(c, "screen off")) scrWant = 0;
  int b;
  if (sscanf(c, "brightness %d", &b) == 1) briWant = b < 0 ? 0 : b > 255 ? 255 : b;
}

static void publishPower(const PowerS &p) {
  char b[320];
  int n = snprintf(b, sizeof b,
    "{\"t\":%lu,\"v\":%.3f,\"i\":%.4f,\"p\":%.3f,\"soc\":%.0f,\"chg\":%d,"
    "\"t_imu\":%.1f,\"t_chip\":%.1f,\"rssi\":%d,\"heap\":%lu,\"mic\":%.1f,"
    "\"avg\":%.3f,\"wh\":%.2f,\"eta\":%.0f,\"scr\":%d,\"bri\":%d}",
    (unsigned long)p.t, p.v, p.i, p.p, p.soc, p.chg, p.tImu, p.tChip, p.rssi, (unsigned long)p.heap, p.mic,
    p.avg, p.wh, p.eta, p.scr, p.bri);
  if (n > 0 && mqtt.publish(MQTT_TOPIC_POWER, b)) pubTotal++;
}

// A slow connect only delays this task; samples are dropped, not backlogged.
static void txTask(void *) {
  Serial.printf("mqtt task on core %d\n", xPortGetCoreID());
  Sample m;
  uint32_t lastIter = millis();
  lastOnline = lastIter; txBeat = lastIter;
  for (;;) {
    uint32_t it = millis();
    if (it - lastIter > 500) Serial.printf("tx stall %u ms (wifi=%d mqtt=%d heap=%u largest=%u)\n", (unsigned)(it - lastIter), (int)wifiUp, (int)mqttUp,
                                           (unsigned)ESP.getFreeHeap(), (unsigned)heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL));
    lastIter = it;
    txBeat = it;
    netService();
    mqttUp = mqtt.connected();
    if (mqttUp) mqttDownSince = 0; else if (wifiUp && !mqttDownSince) mqttDownSince = millis() | 1;
    if (mqttUp) lastOnline = millis();
    else if (millis() - lastOnline > OFFLINE_RESTART_MS) recoveryRestart("no MQTT link");
    if (xQueueReceive(sampleQ, &m, pdMS_TO_TICKS(10)) == pdTRUE && mqttUp) publish(m);
    PowerS pw;
    while (xQueueReceive(powerQ, &pw, 0) == pdTRUE) if (mqttUp) publishPower(pw);
    static AudioChunk ac;
    while (xQueueReceive(audioQ, &ac, 0) == pdTRUE) if (mqttUp && mqtt.publish(MQTT_TOPIC_AUDIO, (const uint8_t *)ac.pcm, sizeof ac.pcm)) pubTotal++;
    uint32_t now = millis();
    if (now - rateT >= 1000) { rateT = now; pubRate = pubCount; pubCount = 0; Serial.printf("pub=%u/s\n", (unsigned)pubRate); }
  }
}

// ---------- setup ----------
void setup() {
  auto cfg = M5.config();
  M5.begin(cfg);
  M5.Display.setRotation(0);                       // native portrait 720x1280
  briLevel = 180;                                  // logical level (~70%); the backlight duty is derived from it
  M5.Display.setBrightness(backlightDuty(briLevel));
  canvas.setColorDepth(lgfx::rgb565_nonswapped);   // match the DSI panel's native format
  canvas.setPsram(false);                          // internal RAM: ~10x faster fills than PSRAM
  if (!canvas.createSprite(SCR_W, STRIP_H)) Serial.println("strip sprite alloc failed");
  bgCache = (uint16_t *)heap_caps_malloc((size_t)CACHE_STRIPS * SCR_W * STRIP_H * 2, MALLOC_CAP_SPIRAM);
  if (!bgCache) Serial.println("panel cache alloc failed");
  canvas.setTextDatum(top_left);

  Serial.begin(115200);
  if (wdMagic != WD_MAGIC) { wdMagic = WD_MAGIC; wdRestarts = 0; }     // RTC_NOINIT memory is garbage after power-on
  if (esp_reset_reason() == ESP_RST_POWERON) wdRestarts = 0;
  Serial.printf("boot: reset reason %d, recovery restarts so far %u, strip %d px\n", (int)esp_reset_reason(), (unsigned)wdRestarts, STRIP_H);
  if (!M5.Imu.isEnabled()) Serial.println("IMU not found");

  WiFi.mode(WIFI_STA);
  wifiClient.setCACert(CA_CERT);
  wifiClient.setHandshakeTimeout(10);
  mqtt.setServer(MQTT_HOST, MQTT_PORT);
  mqtt.setBufferSize(MIC_N * 2 + 64);    // must hold one audio block + topic
  mqtt.setCallback(onMessage);


  mtx = xSemaphoreCreateMutex();
  sampleQ = xQueueCreate(64, sizeof(Sample));
  powerQ  = xQueueCreate(16, sizeof(PowerS));
  audioQ  = xQueueCreate(6, sizeof(AudioChunk));
  i2cMtx  = xSemaphoreCreateMutex();

  // Core 0: graphics. Core 1: sampling (higher prio) and MQTT transmit.
  xTaskCreatePinnedToCore(drawTask,   "gfx",    12288, nullptr, 1, nullptr, CORE_GFX);
  xTaskCreatePinnedToCore(sampleTask, "sample", 6144,  nullptr, 3, nullptr, CORE_IO);
  xTaskCreatePinnedToCore(txTask,     "mqtt",   8192,  nullptr, 2, nullptr, CORE_IO);
  xTaskCreatePinnedToCore(powerTask,  "power",  6144,  nullptr, 2, nullptr, CORE_IO);
  xTaskCreatePinnedToCore(micTask,    "mic",    6144,  nullptr, 2, nullptr, CORE_IO);
}

void loop() { vTaskDelete(nullptr); }              // all work lives in the pinned tasks
