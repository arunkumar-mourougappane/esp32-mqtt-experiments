// Link recovery. The esp-hosted link to the C6 can wedge, and TLS then cannot get enough internal RAM to
// reconnect. Escalate: reset Wi-Fi after a few failed connects, restart the chip if still offline after
// OFFLINE_RESTART_MS or if the tx task stops running for TX_HANG_MS. Give up restarting after MAX_WD_RESTARTS in
// a row without a connection so a dead broker cannot cause a reboot loop.
static constexpr uint32_t OFFLINE_RESTART_MS = 180000;
static constexpr uint32_t TX_HANG_MS         = 60000;
static constexpr int      WIFI_RESET_EVERY   = 3;      // failed MQTT connects
static constexpr uint32_t MAX_WD_RESTARTS    = 3;
static constexpr uint32_t WD_MAGIC           = 0xA5C0FFEE;
