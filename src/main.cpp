static M5Canvas canvas(&M5.Display);               // one STRIP_H-high strip, internal RAM

// Draw target for the current strip: forwards to `canvas` with y shifted by -oy, and skips
// primitives that lie entirely outside the strip. All drawing code is written in screen coordinates.
struct Gx {
  int oy = 0;
  bool out(int y0, int y1) const { return y1 < oy || y0 >= oy + STRIP_H; }
  void fillRect(int x, int y, int w, int h, uint16_t c) { if (!out(y, y + h)) canvas.fillRect(x, y - oy, w, h, c); }
  void drawRect(int x, int y, int w, int h, uint16_t c) { if (!out(y, y + h)) canvas.drawRect(x, y - oy, w, h, c); }
  void fillRoundRect(int x, int y, int w, int h, int r, uint16_t c) { if (!out(y, y + h)) canvas.fillRoundRect(x, y - oy, w, h, r, c); }
  void drawFastHLine(int x, int y, int w, uint16_t c) { if (!out(y, y)) canvas.drawFastHLine(x, y - oy, w, c); }
  void drawFastVLine(int x, int y, int h, uint16_t c) { if (!out(y, y + h)) canvas.drawFastVLine(x, y - oy, h, c); }
  void drawLine(int x0, int y0, int x1, int y1, uint16_t c) {
    if (out(y0 < y1 ? y0 : y1, y0 < y1 ? y1 : y0)) return;
    canvas.drawLine(x0, y0 - oy, x1, y1 - oy, c);
  }
  void drawCircle(int x, int y, int r, uint16_t c) { if (!out(y - r, y + r)) canvas.drawCircle(x, y - oy, r, c); }
  void fillCircle(int x, int y, int r, uint16_t c) { if (!out(y - r, y + r)) canvas.fillCircle(x, y - oy, r, c); }
  void drawArc(int x, int y, int r0, int r1, float a0, float a1, uint16_t c) { if (!out(y - r0, y + r0)) canvas.drawArc(x, y - oy, r0, r1, a0, a1, c); }
  void fillArc(int x, int y, int r0, int r1, float a0, float a1, uint16_t c) { if (!out(y - r0, y + r0)) canvas.fillArc(x, y - oy, r0, r1, a0, a1, c); }
  void drawString(const char *t, int x, int y) { if (!out(y, y + 8 * textSize)) canvas.drawString(t, x, y - oy); }
  void drawCenterString(const char *t, int x, int y) { if (!out(y, y + 8 * textSize)) canvas.drawCenterString(t, x, y - oy); }
  void setTextSize(int sz) { textSize = sz; canvas.setTextSize(sz); }
  void setTextColor(uint16_t c) { canvas.setTextColor(c); }
  uint16_t color565(int r, int gr, int b) { return canvas.color565(r, gr, b); }
  int width() const { return SCR_W; }
  int textSize = 1;
};
