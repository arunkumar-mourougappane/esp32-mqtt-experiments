static volatile int      gfxFps;      // for the memory log line

static void memLine(const char *tag) {
  Serial.printf("%s: internal free=%u largest=%u min=%u fps=%d\n", tag,
                (unsigned)heap_caps_get_free_size(MALLOC_CAP_INTERNAL),
                (unsigned)heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL),
                (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_INTERNAL), (int)gfxFps);
}

static void recoveryRestart(const char *why) {
  if (wdRestarts >= MAX_WD_RESTARTS) return;           // already tried; keep retrying in place
  wdRestarts++;
  Serial.printf("RECOVERY restart %u/%u: %s\n", (unsigned)wdRestarts, (unsigned)MAX_WD_RESTARTS, why);
  memLine("RECOVERY mem");
  Serial.flush();
  delay(100);
  ESP.restart();
}
