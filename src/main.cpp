static void panel(int y, int h) { g.fillRoundRect(12, y, g.width() - 24, h, 8, C_PANEL); }

static void drawScope(const Snap &s, int y0, int h) {
  panel(y0, h);
  const int cx = 300, cy = y0 + 255, R = 170;
  g.setTextSize(2); g.setTextColor(C_TXT);
  g.drawString("ACCEL  g-force scope", 28, y0 + 12);

  float mag = sqrtf(s.a[0] * s.a[0] + s.a[1] * s.a[1] + s.a[2] * s.a[2]);
  char b[48];
  g.setTextSize(4); g.setTextColor(mag > 1.5f ? C_X : C_TXT);
  snprintf(b, sizeof b, "%.2f g", mag);
  g.drawString(b, 28, y0 + 44);

  // grid: rings every 0.5 g, crosshair
  for (int i = 1; i <= 4; i++) g.drawCircle(cx, cy, R * i / 4, i == 2 ? C_DIM : C_GRID);
  g.drawFastHLine(cx - R, cy, 2 * R, C_GRID);
  g.drawFastVLine(cx, cy - R, 2 * R, C_GRID);
  g.setTextSize(1); g.setTextColor(C_DIM);
  g.drawString("1g", cx + R / 2 + 3, cy + 3);
  g.drawString("2g", cx + R + 3, cy + 3);

  auto pos = [&](int idx, int &px, int &py) {
    float x = s.accHist[0][idx], y = s.accHist[1][idx];
    float m = sqrtf(x * x + y * y);
    if (m > SCOPE_G) { x *= SCOPE_G / m; y *= SCOPE_G / m; }
    px = cx + (int)(x / SCOPE_G * R);
    py = cy - (int)(y / SCOPE_G * R);
  };

  // fading trail, oldest -> newest
  for (int i = 0; i < TRAIL; i++) {
    int idx = (s.head - TRAIL + i + 2 * HIST) % HIST;
    int px, py; pos(idx, px, py);
    int k = 40 + (i * 215) / TRAIL;                           // 40..255
    g.fillCircle(px, py, 3 + i * 8 / TRAIL, g.color565(0, k * 3 / 4, k));
  }
  int bx, by; pos((s.head - 1 + HIST) % HIST, bx, by);
  for (int w = -1; w <= 1; w++) g.drawLine(cx + w, cy, bx + w, by, C_DIM);
  g.fillCircle(bx, by, 17, C_Y);
  g.drawCircle(bx, by, 18, C_TXT);

  // Z bar (+/-2 g)
  const int zx = 640, zw = 28, zt = cy - R, zh = 2 * R;
  g.drawRect(zx, zt, zw, zh, C_GRID);
  g.drawFastHLine(zx - 4, cy, zw + 8, C_DIM);
  float z = fmaxf(-SCOPE_G, fminf(SCOPE_G, s.a[2]));
  int zl = (int)(fabsf(z) / SCOPE_G * R);
  if (z >= 0) g.fillRect(zx + 2, cy - zl, zw - 4, zl, C_Z);
  else        g.fillRect(zx + 2, cy,      zw - 4, zl, C_Z);
  g.setTextSize(2); g.setTextColor(C_Z); g.drawString("Z", zx + 6, zt - 24);

  // numbers
  g.setTextSize(2);
  for (int a = 0; a < 3; a++) {
    g.setTextColor(AXC[a]);
    snprintf(b, sizeof b, "%c %+5.2f", "XYZ"[a], s.a[a]);
    g.drawString(b, 28 + a * 220, y0 + h - 36);
  }
}

static void drawDials(const Snap &s, int y0, int h) {
  panel(y0, h);
  g.setTextSize(2); g.setTextColor(C_TXT);
  g.drawString("GYRO  rate dps", 28, y0 + 12);
  const int R = 88, cy = y0 + 140;
  for (int a = 0; a < 3; a++) {
    int cx = 128 + a * 232;
    float v = fmaxf(-GYR_RANGE_D, fminf(GYR_RANGE_D, s.g[a]));
    float sweep = v / GYR_RANGE_D * 135.0f;                    // deg, clockwise positive
    g.drawArc(cx, cy, R, R - 2, 135, 405, C_GRID);         // scale: 270 deg, gap at the bottom
    if (sweep >= 0) g.fillArc(cx, cy, R - 4, R - 20, 270, 270 + sweep, AXC[a]);
    else            g.fillArc(cx, cy, R - 4, R - 20, 270 + sweep, 270, AXC[a]);
    float th = (270.0f + sweep) * DEG_TO_RAD;
    int nx = cx + (int)((R - 24) * cosf(th)), ny = cy + (int)((R - 24) * sinf(th));
    for (int w = -1; w <= 1; w++) g.drawLine(cx + w, cy, nx + w, ny, C_TXT);
    g.fillCircle(cx, cy, 6, C_TXT);
    g.setTextColor(AXC[a]); g.setTextSize(3);
    char b[24]; snprintf(b, sizeof b, "%c", "XYZ"[a]);
    g.drawCenterString(b, cx, cy + 22);
    g.setTextSize(2); g.setTextColor(C_TXT);
    snprintf(b, sizeof b, "%+.0f", s.g[a]);
    g.drawCenterString(b, cx, cy + 56);
  }
}

