// Colours (RGB565). Black bg lets fillSprite use the fast memset path.
static const uint16_t C_BG = 0x0000, C_PANEL = 0x10A2, C_GRID = 0x39E7, C_TXT = 0xFFFF, C_DIM = 0x8C71;
static const uint16_t C_X = 0xF9A6, C_Y = 0x5FEA, C_Z = 0x5D7F;
static const uint16_t AXC[3] = {C_X, C_Y, C_Z};

// ---------- sampling-side maths (sampleTask only) ----------
static void orientation(float ax, float ay, float az, float gx, float gy, float gz, float dt,
                        float &roll, float &pitch, float &yaw) {
  float accRoll  = atan2f(ay, az);
  float accPitch = atan2f(-ax, sqrtf(ay * ay + az * az));
  const float a = 0.98f;
  roll  = a * (roll  + gx * DEG_TO_RAD * dt) + (1 - a) * accRoll;
  pitch = a * (pitch + gy * DEG_TO_RAD * dt) + (1 - a) * accPitch;
  yaw  += gz * DEG_TO_RAD * dt;               // no magnetometer: yaw drifts
  if (yaw >  M_PI) yaw -= 2 * M_PI;
  if (yaw < -M_PI) yaw += 2 * M_PI;
}

// ---------- drawing (drawTask only; reads only its private snapshot) ----------
static void panel(int y, int h) { g.fillRoundRect(12, y, g.width() - 24, h, 8, C_PANEL); }

static void drawScope(const Snap &s, int y0, int h) {
  panel(y0, h);
  const int cx = 300, cy = y0 + 255, R = 170;
  g.setTextSize(2); g.setTextColor(C_TXT);
  g.drawString("ACCEL  g-force scope", 28, y0 + 12);

  float mag = sqrtf(s.a[0] * s.a[0] + s.a[1] * s.a[1] + s.a[2] * s.a[2]);
  char b[48];
  g.setTextSize(4); g.setTextColor(mag > 1.5f ? C_X : C_TXT);
  snprintf(b, sizeof b, "%.2f g", mag);
  g.drawString(b, 28, y0 + 44);

  // grid: rings every 0.5 g, crosshair
  for (int i = 1; i <= 4; i++) g.drawCircle(cx, cy, R * i / 4, i == 2 ? C_DIM : C_GRID);
  g.drawFastHLine(cx - R, cy, 2 * R, C_GRID);
  g.drawFastVLine(cx, cy - R, 2 * R, C_GRID);
  g.setTextSize(1); g.setTextColor(C_DIM);
  g.drawString("1g", cx + R / 2 + 3, cy + 3);
  g.drawString("2g", cx + R + 3, cy + 3);

  auto pos = [&](int idx, int &px, int &py) {
    float x = s.accHist[0][idx], y = s.accHist[1][idx];
    float m = sqrtf(x * x + y * y);
    if (m > SCOPE_G) { x *= SCOPE_G / m; y *= SCOPE_G / m; }
    px = cx + (int)(x / SCOPE_G * R);
    py = cy - (int)(y / SCOPE_G * R);
  };

  // fading trail, oldest -> newest
  for (int i = 0; i < TRAIL; i++) {
    int idx = (s.head - TRAIL + i + 2 * HIST) % HIST;
    int px, py; pos(idx, px, py);
    int k = 40 + (i * 215) / TRAIL;                           // 40..255
    g.fillCircle(px, py, 3 + i * 8 / TRAIL, g.color565(0, k * 3 / 4, k));
  }
  int bx, by; pos((s.head - 1 + HIST) % HIST, bx, by);
  for (int w = -1; w <= 1; w++) g.drawLine(cx + w, cy, bx + w, by, C_DIM);
  g.fillCircle(bx, by, 17, C_Y);
  g.drawCircle(bx, by, 18, C_TXT);

  // Z bar (+/-2 g)
  const int zx = 640, zw = 28, zt = cy - R, zh = 2 * R;
  g.drawRect(zx, zt, zw, zh, C_GRID);
  g.drawFastHLine(zx - 4, cy, zw + 8, C_DIM);
  float z = fmaxf(-SCOPE_G, fminf(SCOPE_G, s.a[2]));
  int zl = (int)(fabsf(z) / SCOPE_G * R);
  if (z >= 0) g.fillRect(zx + 2, cy - zl, zw - 4, zl, C_Z);
  else        g.fillRect(zx + 2, cy,      zw - 4, zl, C_Z);
  g.setTextSize(2); g.setTextColor(C_Z); g.drawString("Z", zx + 6, zt - 24);

  // numbers
  g.setTextSize(2);
  for (int a = 0; a < 3; a++) {
    g.setTextColor(AXC[a]);
    snprintf(b, sizeof b, "%c %+5.2f", "XYZ"[a], s.a[a]);
    g.drawString(b, 28 + a * 220, y0 + h - 36);
  }
}

static void drawDials(const Snap &s, int y0, int h) {
  panel(y0, h);
  g.setTextSize(2); g.setTextColor(C_TXT);
  g.drawString("GYRO  rate dps", 28, y0 + 12);
  const int R = 88, cy = y0 + 140;
  for (int a = 0; a < 3; a++) {
    int cx = 128 + a * 232;
    float v = fmaxf(-GYR_RANGE_D, fminf(GYR_RANGE_D, s.g[a]));
    float sweep = v / GYR_RANGE_D * 135.0f;                    // deg, clockwise positive
    g.drawArc(cx, cy, R, R - 2, 135, 405, C_GRID);         // scale: 270 deg, gap at the bottom
    if (sweep >= 0) g.fillArc(cx, cy, R - 4, R - 20, 270, 270 + sweep, AXC[a]);
    else            g.fillArc(cx, cy, R - 4, R - 20, 270 + sweep, 270, AXC[a]);
    float th = (270.0f + sweep) * DEG_TO_RAD;
    int nx = cx + (int)((R - 24) * cosf(th)), ny = cy + (int)((R - 24) * sinf(th));
    for (int w = -1; w <= 1; w++) g.drawLine(cx + w, cy, nx + w, ny, C_TXT);
    g.fillCircle(cx, cy, 6, C_TXT);
    g.setTextColor(AXC[a]); g.setTextSize(3);
    char b[24]; snprintf(b, sizeof b, "%c", "XYZ"[a]);
    g.drawCenterString(b, cx, cy + 22);
    g.setTextSize(2); g.setTextColor(C_TXT);
    snprintf(b, sizeof b, "%+.0f", s.g[a]);
    g.drawCenterString(b, cx, cy + 56);
  }
}

static void drawLinear(const Snap &s, int y0, int h) {
  panel(y0, h);
  g.setTextSize(2); g.setTextColor(C_TXT);
  g.drawString("LINEAR ACCEL  (gravity removed)", 28, y0 + 12);
  char b[24];
  const int px = 24, pw = g.width() - 48, py = y0 + 76, ph = h - 92;
  for (int a = 0; a < 3; a++) {
    g.setTextColor(AXC[a]);
    int i = (s.head - 1 + HIST) % HIST;
    snprintf(b, sizeof b, "%c %+5.2f", "XYZ"[a], s.linHist[a][i]);
    g.drawString(b, 28 + a * 220, y0 + 44);
  }
  g.drawRect(px, py, pw, ph, C_GRID);
  g.drawFastHLine(px, py + ph / 2, pw, C_GRID);
  g.setTextSize(1); g.setTextColor(C_DIM);
  g.drawString("+1g", px + 4, py + 3);
  g.drawString("-1g", px + 4, py + ph - 12);
  for (int a = 0; a < 3; a++) {
    int ppx = 0, ppy = 0;
    for (int i = 0; i < HIST; i += 2) {                         // decimate: half the line draws
      float v = fmaxf(-LIN_RANGE_G, fminf(LIN_RANGE_G, s.linHist[a][(s.head + i) % HIST]));
      int sx = px + i * (pw - 1) / (HIST - 1);
      int sy = py + ph / 2 - (int)(v / LIN_RANGE_G * (ph / 2 - 2));
      if (i) { g.drawLine(ppx, ppy, sx, sy, AXC[a]); g.drawLine(ppx, ppy + 1, sx, sy + 1, AXC[a]); }
      ppx = sx; ppy = sy;
    }
  }
}

// "3h 12m", "45m", "99+h"
static void fmtEta(char *o, size_t n, float min) {
  if (min < 0) snprintf(o, n, "--");
  else if (min < 1) snprintf(o, n, "<1m");
  else if (min < 60) snprintf(o, n, "%.0fm", min);
  else if (min < 6000) snprintf(o, n, "%dh %02dm", (int)(min / 60), (int)fmodf(min, 60.0f));
  else snprintf(o, n, "99+h");
}

static void drawPower(const Snap &s, int y0, int h) {
  panel(y0, h);
  const PowerS &p = s.pw;
  char b[64];
  g.setTextSize(2); g.setTextColor(C_TXT);
  g.drawString("POWER  battery (2S pack)", 28, y0 + 12);
  const char *st = p.chg > 0 ? "CHARGING" : p.chg < 0 ? "DISCHARGING" : "IDLE";
  g.setTextColor(p.chg > 0 ? C_Y : p.chg < 0 ? C_X : C_DIM);
  g.drawString(st, 440, y0 + 12);

  g.setTextSize(4);                                      // magnitudes only; the state label carries the direction
  uint16_t sc = p.chg > 0 ? C_Y : p.chg < 0 ? C_X : C_DIM;
  g.setTextColor(C_Z);   snprintf(b, sizeof b, "%.2fV", p.v);            g.drawString(b, 28, y0 + 40);
  g.setTextColor(C_TXT); snprintf(b, sizeof b, "%.2fA", fabsf(p.i));     g.drawString(b, 250, y0 + 40);
  g.setTextColor(sc);    snprintf(b, sizeof b, "%.2fW", fabsf(p.p));     g.drawString(b, 470, y0 + 40);

  g.setTextSize(2); g.setTextColor(C_DIM);
  char eta[16]; fmtEta(eta, sizeof eta, p.eta);
  char rs[16];  if (p.rssi) snprintf(rs, sizeof rs, "%d dBm", p.rssi); else snprintf(rs, sizeof rs, "no signal");
  if (p.eta < 0)  snprintf(b, sizeof b, "%.0f%%  %.1f Wh stored  no drain to estimate", p.soc, p.wh);
  else            snprintf(b, sizeof b, "%.0f%%  %.1f Wh  %s %s at %.1f W avg", p.soc, p.wh,
                           p.avg < 0 ? "left" : "to full", eta, fabsf(p.avg));
  g.drawString(b, 28, y0 + 84);
  if (micOn) snprintf(b, sizeof b, "MIC LIVE %.0f dBFS  %s  heap %uk", p.mic, rs, (unsigned)(p.heap / 1024));
  else       snprintf(b, sizeof b, "IMU %.1fC  chip %.0fC  %s  heap %uk", p.tImu, p.tChip, rs, (unsigned)(p.heap / 1024));
  g.setTextColor(micOn ? C_X : C_DIM);
  g.drawString(b, 28, y0 + 108);

  // 30 s power history, +/-PWR_RANGE_W
  const int px = 24, pw = g.width() - 48, py = y0 + 136, ph = h - 148;
  g.drawRect(px, py, pw, ph, C_GRID);
  g.drawFastHLine(px, py + ph / 2, pw, C_GRID);
  g.setTextSize(1); g.setTextColor(C_DIM);
  g.drawString("charging", px + 4, py + 3);
  g.drawString("discharging", px + 4, py + ph - 12);
  int ppx = 0, ppy = 0;
  for (int i = 0; i < PHIST; i += 2) {
    float v = fmaxf(-PWR_RANGE_W, fminf(PWR_RANGE_W, s.pHist[(s.pHead + i) % PHIST]));
    int sx = px + i * (pw - 1) / (PHIST - 1);
    int sy = py + ph / 2 - (int)(v / PWR_RANGE_W * (ph / 2 - 2));
    if (i) { g.drawLine(ppx, ppy, sx, sy, C_Y); g.drawLine(ppx, ppy + 1, sx, sy + 1, C_Y); }
    ppx = sx; ppy = sy;
  }
}

