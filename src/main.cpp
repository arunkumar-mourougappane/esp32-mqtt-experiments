// M5Stack Tab5: IMU (BMI270) visualizer + MQTT streamer.
//
// Tasks:  gfx (core 0)  - draws from a locked snapshot of the latest data
//         sample (core 1) - 100 Hz IMU read, orientation filter, writes shared state
//         power (core 1)  - 10 Hz battery V/I/P (INA226), temperatures, RSSI, mic level
//         mqtt (core 1)   - owns WiFi + MQTT, publishes imu 50 Hz (tab5/imu) + power 10 Hz (tab5/power)
//
// Display (portrait 720x1280 = the panel's native orientation; landscape costs ~15x in pushSprite).
// Rendering: 160-px strips drawn into a small internal-RAM sprite (10x faster than PSRAM) and pushed
// one by one, instead of one full-screen PSRAM sprite:
//   g-force scope (accel x/y ball + trail, z bar), gyro rate dials, linear-accel history.
