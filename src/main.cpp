// ---------- sampling-side maths (sampleTask only) ----------
static void orientation(float ax, float ay, float az, float gx, float gy, float gz, float dt,
                        float &roll, float &pitch, float &yaw) {
  float accRoll  = atan2f(ay, az);
  float accPitch = atan2f(-ax, sqrtf(ay * ay + az * az));
  const float a = 0.98f;
  roll  = a * (roll  + gx * DEG_TO_RAD * dt) + (1 - a) * accRoll;
  pitch = a * (pitch + gy * DEG_TO_RAD * dt) + (1 - a) * accPitch;
  yaw  += gz * DEG_TO_RAD * dt;               // no magnetometer: yaw drifts
  if (yaw >  M_PI) yaw -= 2 * M_PI;
  if (yaw < -M_PI) yaw += 2 * M_PI;
}

